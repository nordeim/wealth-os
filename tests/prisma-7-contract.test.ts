import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

// Session-213 (R-9, the prisma 6→7 major migration — the plan v2.10.0
// contract pin): the ORM major changes WHERE the client lives and HOW it
// connects, and every one of those seams is load-bearing for the repo's
// db-path doctrine (the single most-tested module family in the template).
// These pins freeze the migration's GREEN shape so a partial regression —
// a reverted generator, a datasources-stray constructor, a removed
// postinstall — fails loudly instead of drifting silently:
//
//   1. schema.prisma: the `prisma-client` generator (NOT the removed-era
//      `prisma-client-js`) with an explicit output path — the client no
//      longer lands in node_modules.
//   2. The two PrismaClient constructors (src/lib/db.ts + prisma/seed.ts —
//      the ONLY two in the tree): built through the
//      @prisma/adapter-better-sqlite3 driver adapter, importing the
//      generated client, and passing NO removed `datasources` option. The
//      URL still comes from runtimeDatabaseUrl() — the db-path seam
//      survives the major unchanged.
//   3. prisma.config.ts at the repo root: the CLI's config home (schema
//      path + the datasource seam routed through resolveDatabaseUrl so a
//      relative URL can never ride the v7 CWD rule out of the repo).
//   4. tests/e2e/global-setup.ts: no removed `--skip-generate` flag, and
//      the e2e database pinned by ABSOLUTE url (the v6 schema-relative
//      rule is gone; a relative URL under prisma.config.ts resolves
//      against the CLI's CWD).
//   5. The generated client dir (src/generated) is gitignored AND
//      eslint-ignored — regenerated by the postinstall, never committed,
//      never linted.
//   6. package.json: `postinstall: prisma generate` (the fresh-clone DX
//      contract — `bun install` yields a typecheckable tree), prisma in
//      devDependencies (the CLI is not runtime), the adapter chain in
//      dependencies, and the bun allowScripts keys tracking 7.x.

const ROOT = path.resolve(import.meta.dirname, "..");
const read = (rel: string): string => readFileSync(path.join(ROOT, rel), "utf-8");
const norm = (s: string): string => s.replace(/\s+/g, " ");

describe("session-213: the prisma-7 migration contract (R-9 — the seam changes are pinned)", () => {
  it("schema.prisma uses the prisma-client generator with an explicit output path", () => {
    const schema = read("prisma/schema.prisma");
    const generatorBlock = /generator\s+client\s*\{[^}]*\}/.exec(schema);
    expect(generatorBlock, "no `generator client` block in prisma/schema.prisma").not.toBeNull();
    const block = generatorBlock![0];
    expect(
      block,
      "the generator must be `prisma-client` — the prisma-client-js provider is the removed v6-era form",
    ).toMatch(/provider\s*=\s*"prisma-client"/);
    expect(block).not.toMatch(/prisma-client-js/);
    expect(
      block,
      "the generator block must pin an `output` path (required in v7 — the client no longer lands in node_modules)",
    ).toMatch(/output\s*=\s*"/);
  });

  it("both PrismaClient constructors build through the driver adapter — no removed `datasources` option, generated-client imports, db-path seam intact", () => {
    for (const rel of ["src/lib/db.ts", "prisma/seed.ts"]) {
      const src = read(rel);
      expect(
        src,
        `${rel}: must import the driver adapter (the v7 client requires one)`,
      ).toMatch(/from\s+"@prisma\/adapter-libsql"/);
      expect(
        norm(src),
        `${rel}: must construct the adapter with the db-path seam's URL (runtimeDatabaseUrl)`,
      ).toContain("new PrismaLibSql({ url: runtimeDatabaseUrl() })");
      expect(
        src,
        `${rel}: the PrismaClient import must come from the generated client, not @prisma/client`,
      ).not.toMatch(/from\s+"@prisma\/client"/);
      expect(
        src,
        `${rel}: the removed v6 'datasources' constructor option must be gone (silently ignored at best, fatal at worst)`,
      ).not.toContain("datasources");
    }
    // The db-path seam itself is untouched by the major.
    expect(read("src/lib/db.ts")).toMatch(/runtimeDatabaseUrl\(\)/);
  });

  it("prisma.config.ts exists at the root with the schema path and the seam-routed datasource URL", () => {
    const configPath = path.join(ROOT, "prisma.config.ts");
    expect(existsSync(configPath), "prisma.config.ts missing at the repo root").toBe(true);
    const config = read("prisma.config.ts");
    expect(config).toContain("defineConfig");
    expect(config).toMatch(/schema:\s*"prisma\/schema\.prisma"/);
    expect(
      norm(config),
      "the datasource URL must route through resolveDatabaseUrl (the db-path seam) so a relative URL can never ride the v7 CWD rule out of the repo",
    ).toContain("resolveDatabaseUrl(");
  });

  it("the e2e global-setup carries no removed --skip-generate flag and pins the e2e database by ABSOLUTE url", () => {
    const setup = read("tests/e2e/global-setup.ts");
    expect(
      setup,
      "`--skip-generate` was REMOVED in prisma 7 — the flag now errors",
    ).not.toContain("--skip-generate");
    expect(
      norm(setup),
      "the e2e db push must pin its target by absolute url (the v6 schema-relative resolution moved to prisma.config.ts)",
    ).toMatch(/file:\$\{path\.join\(/);
    // The validated-root guard: the absolute pin must be anchored on a
    // root that actually carries prisma/schema.prisma (the db-path
    // idiom, inlined — Playwright loads this file as CJS).
    expect(setup).toContain('path.join(root, "prisma", "schema.prisma")');
  });

  it("the generated client dir is gitignored and eslint-ignored (regenerated, never committed, never linted)", () => {
    expect(read(".gitignore")).toMatch(/src\/generated/);
    const eslint = read("eslint.config.mjs");
    expect(norm(eslint)).toContain("src/generated");
  });

  it("package.json wires the migration: postinstall generate, prisma in devDependencies, the adapter chain in dependencies, allowScripts on 7.x", () => {
    const pkg = JSON.parse(read("package.json")) as {
      scripts?: Record<string, string>;
      dependencies?: Record<string, string>;
      devDependencies?: Record<string, string>;
      allowScripts?: Record<string, boolean>;
      trustedDependencies?: string[];
    };
    expect(
      pkg.scripts?.postinstall,
      "the postinstall must regenerate the client (fresh-clone DX: `bun install` yields a typecheckable tree)",
    ).toBe("prisma generate");
    expect(
      pkg.devDependencies?.prisma,
      "the prisma CLI belongs in devDependencies (it is not runtime code)",
    ).toMatch(/\^7\./);
    expect(pkg.dependencies?.prisma, "prisma must NOT ride the runtime dependencies").toBeUndefined();
    expect(pkg.dependencies?.["@prisma/client"], "the runtime client must be 7.x").toMatch(/\^7\./);
    expect(
      pkg.dependencies?.["@prisma/adapter-libsql"],
      "the driver adapter is a runtime dependency now",
    ).toMatch(/\^7\./);
    expect(
      pkg.dependencies?.["@libsql/client"],
      "the adapter's libsql driver must be an explicit runtime dependency (the bun-compatible SQLite chain)",
    ).toMatch(/\^0\.17\./);
    expect(
      pkg.dependencies?.["better-sqlite3"],
      "better-sqlite3 must NOT ride the dependencies — bun blocks its constructor (oven-sh/bun#4290)",
    ).toBeUndefined();
    expect(
      pkg.allowScripts?.["prisma@7.10.1"],
      "the bun allowScripts keys must track the 7.x resolutions",
    ).toBe(true);
  });

  it("next.config.ts externalizes the native adapter chain from the server bundle", () => {
    const config = read("next.config.ts");
    for (const pkgName of [
      "@prisma/adapter-libsql",
      "@libsql/client",
      "@prisma/client-runtime-utils",
    ]) {
      expect(
        config,
        `${pkgName} must be in serverExternalPackages (native/wasm-loading code must not be webpack-bundled)`,
      ).toContain(pkgName);
    }
  });
});
